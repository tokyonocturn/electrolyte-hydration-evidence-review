# --------------------------------------------------------------------------- io


def read_csv(name: str, columns: list[str], delimiter: str = ",") -> list[dict[str, str]]:
    path = DATA / name
    if not path.exists():
        sys.exit(f"error: missing dataset {path}")
    with path.open(newline="", encoding="utf-8") as fh:
        reader = csv.DictReader(fh, delimiter=delimiter)
        if reader.fieldnames != columns:
            sys.exit(
                f"error: {name} columns differ\n  expected: {columns}\n  found:    {reader.fieldnames}"
            )
        rows = []
        for line_no, row in enumerate(reader, start=2):
            if None in row:
                sys.exit(f"error: {name}:{line_no}: too many fields")
            rows.append({k: (v or "").strip() for k, v in row.items()})
    return rows


BLANKS = {"", "NA", "n/a", "n/a"}


def num(value: str, field: str, row_id: str, allow_blank: bool = False) -> float | None:
    if value in BLANKS:
        if allow_blank:
            return None
        sys.exit(f"error: {row_id}: {field} is blank")
    try:
        return float(value)
    except ValueError:
        sys.exit(f"error: {row_id}: {field} is not a number: {value!r}")


def money(x: float) -> str:
    return f"${x:,.2f}"


def f0(x: float | None) -> str:
    return "n/a" if x is None else f"{x:,.0f}"


def f1(x: float | None) -> str:
    return "n/a" if x is None else f"{x:,.1f}"


def esc(text: str) -> str:
    return text.replace("|", "\\|")


def table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        out.append("| " + " | ".join(cell if cell != "" else "n/a" for cell in row) + " |")
    return "\n".join(out) + "\n"


def sorted_refs(ids: str) -> str:
    if not ids:
        return "n/a"
    return ", ".join(sorted(ids.split(), key=lambda r: int(re.sub(r"\D", "", r) or 0)))


