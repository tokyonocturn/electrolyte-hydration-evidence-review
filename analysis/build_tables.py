"""Validate the electrolyte datasets and regenerate every Markdown table.

The CSV files in ../data are the single source of truth. Nothing in
docs/generated/ or docs/references.md is edited by hand: this script rebuilds
them, and `--check` fails when a committed file is stale or a relative link
does not resolve.

Usage:
    python analysis/build_tables.py            # validate + regenerate
    python analysis/build_tables.py --check    # fail if outputs are stale
"""

