def validate_products(rows: list[dict[str, str]]) -> None:
    seen = set()
    for r in rows:
        pid = r["id"]
        if not pid or pid in seen:
            sys.exit(f"error: duplicate or blank product id {pid!r}")
        seen.add(pid)
        if r["category"] not in CATEGORIES:
            sys.exit(f"error: {pid}: category {r['category']!r} not allowed")
        if r["format"] not in FORMATS:
            sys.exit(f"error: {pid}: format {r['format']!r} not allowed")
        if r["sweetener_class"] not in SWEETENER_CLASSES:
            sys.exit(f"error: {pid}: sweetener_class {r['sweetener_class']!r} not allowed")
        water = num(r["water_ml"], "water_ml", pid)
        servings = num(r["servings"], "servings", pid)
        price = num(r["price_usd"], "price_usd", pid)
        if water <= 0 or servings <= 0 or price <= 0:
            sys.exit(f"error: {pid}: water_ml, servings and price_usd must be positive")
        na = num(r["na_mg"], "na_mg", pid)
        k = num(r["k_mg"], "k_mg", pid)
        mg = num(r["mg_mg"], "mg_mg", pid)
        ca = num(r["ca_mg"], "ca_mg", pid)
        cl = num(r["cl_mg"], "cl_mg", pid, allow_blank=True)
        carb = num(r["carb_g"], "carb_g", pid)
        sugar = num(r["sugar_g"], "sugar_g", pid)
        for label, value in (("na_mg", na), ("k_mg", k), ("mg_mg", mg), ("ca_mg", ca)):
            if value < 0:
                sys.exit(f"error: {pid}: {label} cannot be negative")
        if cl is not None and cl < 0:
            sys.exit(f"error: {pid}: cl_mg cannot be negative")
        if carb < 0 or sugar < 0:
            sys.exit(f"error: {pid}: carbohydrate values cannot be negative")
        if sugar > carb + 0.05:
            sys.exit(f"error: {pid}: sugar_g exceeds carb_g")
        for flag in ("na_decl", "k_decl", "mg_decl", "ca_decl", "cl_decl"):
            if r[flag] not in {"Y", "N"}:
                sys.exit(f"error: {pid}: {flag} must be Y or N")
        if r["na_decl"] == "N" and na != 0:
            sys.exit(f"error: {pid}: undeclared sodium must be recorded as 0")
        if r["cl_decl"] == "N" and cl not in (None, 0.0, ""):
            sys.exit(f"error: {pid}: cl_decl is N but cl_mg is set")
        if r["cl_decl"] == "Y" and cl is None:
            sys.exit(f"error: {pid}: cl_decl is Y but cl_mg is blank")
        if not r["price_date"].startswith("2026-"):
            sys.exit(f"error: {pid}: price_date must be a 2026 snapshot date")
        if not r["price_url"].startswith("https://") or not r["label_url"].startswith("https://"):
            sys.exit(f"error: {pid}: price_url and label_url must be https")


def validate_evidence(rows: list[dict[str, str]], ref_ids: set[str]) -> None:
    seen = set()
    for r in rows:
        eid = r["id"]
        if not eid or eid in seen:
            sys.exit(f"error: duplicate or blank evidence id {eid!r}")
        seen.add(eid)
        if r["domain"] not in DOMAINS:
            sys.exit(f"error: {eid}: domain {r['domain']!r} not allowed")
        if r["status"] not in STATUSES:
            sys.exit(f"error: {eid}: status {r['status']!r} not allowed")
        if r["certainty"] not in CERTAINTIES:
            sys.exit(f"error: {eid}: certainty {r['certainty']!r} not allowed")
        if r["reference_id"] not in ref_ids:
            sys.exit(f"error: {eid}: unknown reference {r['reference_id']!r}")
        n = num(r["n"], "n", eid, allow_blank=True)
        if n is not None and n <= 0:
            sys.exit(f"error: {eid}: n must be positive")
        for field in ("ci_low", "ci_high"):
            num(r[field], field, eid, allow_blank=True)


def validate_claims(rows: list[dict[str, str]], ev_ids: set[str], ref_ids: set[str]) -> None:
    seen = set()
    for r in rows:
        cid = r["id"]
        if not cid or cid in seen:
            sys.exit(f"error: duplicate or blank claim id {cid!r}")
        seen.add(cid)
        if r["verdict"] not in VERDICTS:
            sys.exit(f"error: {cid}: verdict {r['verdict']!r} not allowed")
        for e in r["evidence_ids"].split():
            if e not in ev_ids:
                sys.exit(f"error: {cid}: unknown evidence id {e!r}")
        for e in r["reference_ids"].split():
            if e not in ref_ids:
                sys.exit(f"error: {cid}: unknown reference id {e!r}")


def validate_dosing(rows: list[dict[str, str]], ref_ids: set[str]) -> None:
    for r in rows:
        for ref in r["reference_ids"].split():
            if ref not in ref_ids:
                sys.exit(f"error: dosing row {r['scenario']!r}: unknown reference {ref!r}")
        for field in ("sodium_mg_per_h", "fluid_ml_per_h", "carb_g_per_h", "notes"):
            if not r[field]:
                sys.exit(f"error: dosing row {r['scenario']!r}: {field} is blank")
        for field in ("sodium_mg_per_h", "fluid_ml_per_h", "carb_g_per_h"):
            value = r[field]
            if re.fullmatch(r"[0-9][0-9.,\-– ]*", value):
                num(value.split("-")[0].replace(",", ""), field, r["scenario"])


def validate_standards(rows: list[dict[str, str]], ref_ids: set[str]) -> None:
    seen = set()
    for r in rows:
        if not r["id"] or r["id"] in seen:
            sys.exit(f"error: duplicate or blank standard id {r['id']!r}")
        seen.add(r["id"])
        if r["source_id"] not in ref_ids:
            sys.exit(f"error: {r['id']}: unknown source {r['source_id']!r}")


# --------------------------------------------------------------------- compute


def enrich(products: list[dict[str, str]]) -> list[dict[str, object]]:
    out = []
    for r in products:
        water = float(r["water_ml"])
        servings = float(r["servings"])
        price = float(r["price_usd"])
        na = float(r["na_mg"])
        k = float(r["k_mg"])
        carb = float(r["carb_g"])
        cost_serving = price / servings
        item: dict[str, object] = dict(r)
        item["cost_serving"] = cost_serving
        item["na_mmol_l"] = na / 22.99 / (water / 1000) if na else 0.0
        item["na_mg_l"] = na / (water / 1000) if na else 0.0
        item["salt_g"] = na * 2.542 / 1000
        item["carb_pct"] = carb / (water / 100) if water else 0.0
        item["cost_per_1000na"] = (cost_serving / na * 1000) if na > 0 else None
        item["na_k_mass"] = (na / k) if k > 0 else None
        item["na_k_molar"] = ((na / 22.99) / (k / 39.0983)) if k > 0 else None
        item["declared"] = sum(1 for _, _, flag in NUTRIENTS if r[flag] == "Y")
        out.append(item)
    return out


# --------------------------------------------------------------------- writers


def product_table(rows: list[dict[str, object]]) -> str:
    body = []
    for r in sorted(rows, key=lambda x: (-float(x["na_mg"]), str(x["brand"]))):
        body.append([
            f"{r['brand']} {r['product']}",
            str(r["serving_desc"]),
            f0(float(r["na_mg"])),
            f0(float(r["na_mg_l"])),
            f0(float(r["k_mg"])),
            f0(float(r["mg_mg"])),
            f0(float(r["ca_mg"])),
            f0(float(r["cl_mg"])) if r["cl_decl"] == "Y" else "ND",
            f1(float(r["carb_g"])),
            f1(float(r["sugar_g"])),
            str(r["sweeteners"]),
            money(float(r["cost_serving"])),
            money(float(r["cost_per_1000na"])) if r["cost_per_1000na"] else "n/a",
        ])
    return table(
        ["Product", "Serving", "Na mg", "Na mg/L", "K mg", "Mg mg", "Ca mg",
         "Cl mg", "Carb g", "Sugar g", "Sweetener", "$/serving", "$/1,000 mg Na"],
        body,
    )


def build_product_comparison(products: list[dict[str, object]]) -> str:
    parts = [GENERATED_NOTE, "# Product comparison\n",
             "Sodium is the electrolyte that matters for hydration, so the table is sorted by "
             "sodium per serving. `Na mg/L` is the concentration at the **smallest** dilution the "
             "brand recommends; drinking a stick in more water lowers concentration without "
             "changing the dose. `ND` means the label does not declare the nutrient, it does not "
             "mean zero. Prices are November 2026 snapshots and exclude shipping.\n"]
    for category in sorted(CATEGORIES):
        rows = [r for r in products if r["category"] == category]
        if not rows:
            continue
        parts.append(f"## {category}\n")
        parts.append(product_table(rows))
        parts.append("")
    parts.append("## Notes\n")
    parts.append(
        "A serving is the label's stated serving at the stated dilution, not a bottle or a scoop "
        "the manufacturer happens to sell. Cost per 1,000 mg sodium is the only price metric that "
        "lets a 1,000 mg stick, a 300 mg tablet and a 270 mg bottle be compared. Products with no "
        "declared sodium have no meaningful value on that metric; they are hydration products, not "
        "sodium-replacement products.\n"
    )
    return "\n".join(parts)


def build_value_ranking(products: list[dict[str, object]]) -> str:
    useful = [r for r in products if float(r["na_mg"]) >= 200 and r["cost_per_1000na"]]
    useful.sort(key=lambda r: float(r["cost_per_1000na"]))
    body = []
    for rank, r in enumerate(useful, start=1):
        body.append([
            str(rank),
            f"{r['brand']} {r['product']}",
            str(r["category"]),
            f0(float(r["na_mg"])),
            money(float(r["cost_serving"])),
            money(float(r["cost_per_1000na"])),
            money(float(r["cost_per_1000na"]) / 2),
        ])
    cheap = float(useful[0]["cost_per_1000na"])
    dear = float(useful[-1]["cost_per_1000na"])
    parts = [GENERATED_NOTE, "# Cost per useful sodium dose\n",
             f"{len(useful)} products deliver at least 200 mg sodium per serving. Ranked by cost "
             f"per 1,000 mg sodium, the spread is **{cheap:.2f}×** "
             f"({money(cheap)} to {money(dear)}).\n"]
    parts.append(table(
        ["#", "Product", "Category", "Na mg", "$/serving", "$/1,000 mg Na", "$/500 mg Na"],
        body))
    thin = [r for r in products if float(r["na_mg"]) < 200]
    if thin:
        parts.append("\n## Products that are not meaningful sodium doses\n")
        parts.append(
            "These deliver under 200 mg sodium per serving, less than 15% of a typical "
            "litre of sweat at 40 mmol/L. Their cost per 1,000 mg sodium is either undefined "
            "or absurd, which is itself the finding.\n"
        )
        rows = []
        for r in sorted(thin, key=lambda x: float(x["na_mg"])):
            rows.append([
                f"{r['brand']} {r['product']}",
                f0(float(r["na_mg"])),
                f0(float(r["na_mg_l"])),
                f0(float(r["k_mg"])),
                money(float(r["cost_serving"])),
                money(float(r["cost_per_1000na"])) if r["cost_per_1000na"] else "n/a",
            ])
        parts.append(table(["Product", "Na mg", "Na mg/L", "K mg", "$/serving", "$/1,000 mg Na"], rows))
    return "\n".join(parts)


def build_composition(products: list[dict[str, object]]) -> str:
    n = len(products)
    parts = [GENERATED_NOTE, "# Composition audit\n",
             f"Label transparency and electrolyte balance across {n} products.\n",
             "## What the labels declare\n"]
    rows = []
    for _, label, flag in NUTRIENTS:
        count = sum(1 for r in products if r[flag] == "Y")
        rows.append([label, str(count), f"{count / n * 100:.0f}%"])
    parts.append(table(["Electrolyte", "Products declaring an amount", "Share"], rows))
    parts.append(
        "\nChloride is the clearest transparency gap: it is the second most abundant ion in "
        "sweat, yet most labels omit it. Magnesium and calcium are declared mainly by premium "
        "sticks that use them as marketing differentiators, at doses far below daily requirements.\n"
    )

    parts.append("\n## Sodium-to-potassium ratio\n")
    parts.append(
        "Mass ratio (Na:K) and molar ratio are both shown because physiology works in mmol. "
        "Sweat is sodium-dominant (roughly 40 mmol/L sodium against 4–8 mmol/L potassium, a "
        "molar ratio near 6:1); most electrolyte products are far more potassium-heavy than sweat. "
        "That is not dangerous for healthy kidneys, but it is not sweat replacement either.\n"
    )
    rows = []
    for r in sorted([x for x in products if float(x["k_mg"]) > 0],
                    key=lambda x: float(x["na_k_molar"] or 0), reverse=True):
        rows.append([
            f"{r['brand']} {r['product']}",
            f0(float(r["na_mg"])),
            f0(float(r["k_mg"])),
            f"{float(r['na_k_mass']):.1f}" if r["na_k_mass"] else "n/a",
            f"{float(r['na_k_molar']):.1f}" if r["na_k_molar"] else "n/a",
        ])
    parts.append(table(["Product", "Na mg", "K mg", "Na:K mass", "Na:K molar"], rows))

    parts.append("\n## Carbohydrate concentration\n")
    parts.append(
        "Carbohydrate percentage is grams per 100 mL at the stated dilution. Sport-nutrition "
        "guidance puts optimal beverage carbohydrate at roughly 4–9% for simultaneous fueling "
        "and emptying; above ~8% solutions slow gastric emptying and can cause GI distress. "
        "Hypotonic drinks (<4%) hydrate best; concentrated sticks rely on the user adding water.\n"
    )
    rows = []
    for r in sorted(products, key=lambda x: -float(x["carb_pct"])):
        if float(r["carb_g"]) == 0:
            continue
        rows.append([
            f"{r['brand']} {r['product']}",
            f1(float(r["carb_g"])),
            f1(float(r["sugar_g"])),
            f"{float(r['carb_pct']):.1f}%",
            str(r["sweetener_class"]),
        ])
    parts.append(table(["Product", "Carb g", "Sugar g", "Carb % w/v", "Sweetener class"], rows))

    parts.append("\n## Added sugar and non-nutritive sweeteners\n")
    added = sum(1 for r in products if float(r["sugar_g"]) > 0.5)
    zero = sum(1 for r in products if float(r["sugar_g"]) <= 0.5)
    parts.append(
        f"{added} of {n} products contain more than 0.5 g sugar per serving; {zero} are "
        "effectively sugar-free. Sugar is not an impurity in a sports drink, at 30–90 g/h it is "
        "the performance ingredient. In a low-sodium, low-carbohydrate product it is mostly "
        "palatability and calories.\n"
    )
    classes = Counter(str(r["sweetener_class"]) for r in products)
    rows = [[k, str(v)] for k, v in sorted(classes.items(), key=lambda kv: -kv[1])]
    parts.append(table(["Sweetener class", "Products"], rows))
    return "\n".join(parts)


def build_evidence(evidence: list[dict[str, str]], refs: dict[str, dict[str, str]]) -> str:
    parts = [GENERATED_NOTE, "# Evidence tables\n",
             "Every row is a question, the best available answer, and a certainty grade. "
             "`Established` marks physiology that is not seriously disputed; `Benefit`, "
             "`No benefit`, `Harm`, `Mixed` and `Insufficient` describe what the evidence shows "
             "about an intervention. Effect estimates are reported as published; an empty "
             "estimate means the source is qualitative.\n"]
    by_domain: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in evidence:
        by_domain[row["domain"]].append(row)
    for domain in [d for d in DOMAIN_ORDER if d in by_domain]:
        parts.append(f"## {domain}\n")
        rows = []
        for r in sorted(by_domain[domain], key=lambda x: x["id"]):
            estimate = r["estimate"]
            if estimate and r["ci_low"] and r["ci_high"]:
                estimate = f"{estimate} ({r['ci_low']}–{r['ci_high']})"
            if estimate and r["metric"] not in {"n/a", "n/a"} and any(c.isdigit() for c in estimate):
                estimate = f"{estimate} {r['metric']}"
            rows.append([
                r["id"], esc(r["question"]), esc(r["population"]), esc(r["design"]),
                r["n"], esc(estimate) if estimate else "n/a", r["status"], r["certainty"],
                r["reference_id"],
            ])
        parts.append(table(
            ["ID", "Question", "Population", "Design", "n", "Result", "Status", "Certainty", "Ref"],
            rows))
    parts.append("## Counts\n")
    status_rows = [[k, str(v)] for k, v in sorted(Counter(r["status"] for r in evidence).items())]
    parts.append(table(["Status", "Rows"], status_rows))
    return "\n".join(parts)


def build_claims(claims: list[dict[str, str]]) -> str:
    parts = [GENERATED_NOTE, "# Claims, adjudicated\n",
             "Twenty-six claims that appear in marketing, coaching or mainstream advice, each "
             "answered against the evidence table. `Misleading` means the claim is directionally "
             "defensible but omits the condition that decides whether it is true.\n"]
    rows = []
    for r in claims:
        rows.append([
            r["id"], esc(r["claim"]), r["verdict"], esc(r["explanation"]),
            r["evidence_ids"].replace(" ", ", "), sorted_refs(r["reference_ids"]),
        ])
    parts.append(table(["ID", "Claim", "Verdict", "Why", "Evidence", "Refs"], rows))
    parts.append("## Counts\n")
    parts.append(table(["Verdict", "Claims"],
                       [[k, str(v)] for k, v in sorted(Counter(r["verdict"] for r in claims).items())]))
    return "\n".join(parts)


def build_dosing(dosing: list[dict[str, str]]) -> str:
    parts = [GENERATED_NOTE, "# Dosing guidance\n",
             "Targets are for adults with normal kidney function. Sodium is expressed per hour of "
             "exercise; fluid is a starting range to be individualised by sweat rate and tolerance. "
             "`n/a` means the variable is not the point of that row.\n"]
    rows = []
    for r in dosing:
        rows.append([
            esc(r["scenario"]), esc(r["population"]), r["sodium_mg_per_h"],
            r["fluid_ml_per_h"], r["carb_g_per_h"], esc(r["notes"]),
            sorted_refs(r["reference_ids"]),
        ])
    parts.append(table(
        ["Scenario", "Population", "Sodium mg/h", "Fluid mL/h", "Carb g/h", "Notes", "Refs"],
        rows))
    parts.append(
        "\nThese are ranges, not prescriptions. The only reliable way to set an individual fluid "
        "target is to weigh before and after a representative session: 1 kg lost ≈ 1 L deficit. "
        "Sodium targets can be refined with a sweat test, but the test has substantial measurement "
        "error and should change the starting point, not dictate a fixed number.\n"
    )
    return "\n".join(parts)


def build_standards(standards: list[dict[str, str]]) -> str:
    parts = [GENERATED_NOTE, "# Reference values and composition standards\n"]
    rows = []
    for r in standards:
        rows.append([r["id"], esc(r["parameter"]), r["value"], r["unit"],
                     esc(r["applies_to"]), r["source_id"], esc(r["notes"])])
    parts.append(table(
        ["ID", "Parameter", "Value", "Unit", "Applies to", "Source", "Notes"], rows))
    return "\n".join(parts)


def build_references(refs: list[dict[str, str]]) -> str:
    parts = [GENERATED_NOTE, "# References\n",
             f"{len(refs)} sources. DOIs are given where the identifier is known; otherwise a "
             "PMIDs or stable URL is supplied. Product labels are cited in "
             "[product sources](generated/product-sources.md) rather than here.\n"]
    rows = []
    for r in sorted(refs, key=lambda x: int(re.sub(r"\D", "", x["id"]) or 0)):
        if r["doi"]:
            ident = f"[doi:{r['doi']}](https://doi.org/{r['doi']})"
        elif r["pmid"]:
            ident = f"[PMID {r['pmid']}](https://pubmed.ncbi.nlm.nih.gov/{r['pmid']}/)"
        elif r["url"]:
            ident = f"[link]({r['url']})"
        else:
            ident = "n/a"
        rows.append([r["id"], esc(r["citation"]), r["type"], ident])
    parts.append(table(["ID", "Citation", "Type", "Identifier"], rows))
    return "\n".join(parts)


def build_product_sources(products: list[dict[str, str]]) -> str:
    parts = [GENERATED_NOTE, "# Product sources\n",
             "Label and price evidence for every product row. Prices are one-time list prices "
             "collected in November 2026 from the channel named; they are not affiliate links and "
             "no brand paid for inclusion.\n"]
    rows = []
    for r in products:
        rows.append([
            r["id"], esc(r["brand"] + " " + r["product"]),
            f"[label]({r['label_url']})", f"[price]({r['price_url']})",
            esc(r["price_channel"]), r["price_date"], esc(r["certification"]),
        ])
    parts.append(table(
        ["ID", "Product", "Label", "Price", "Channel", "Date", "Certification"], rows))
    return "\n".join(parts)


def build_key_numbers(products: list[dict[str, object]], evidence: list[dict[str, str]]) -> str:
    useful = [r for r in products if float(r["na_mg"]) >= 200 and r["cost_per_1000na"]]
    cheap = min(useful, key=lambda r: float(r["cost_per_1000na"]))
    dear = max(useful, key=lambda r: float(r["cost_per_1000na"]))
    lo = float(cheap["cost_per_1000na"])
    hi = float(dear["cost_per_1000na"])
    zero_na = [r for r in products if float(r["na_mg"]) == 0]
    max_na = max(products, key=lambda r: float(r["na_mg"]))
    parts = [GENERATED_NOTE, "# Key numbers\n",
             "Computed from the datasets so that the prose in the README and reports cannot drift "
             "from the data.\n",
             table(["Metric", "Value"], [
                 ["Products in database", str(len(products))],
                 ["Products delivering ≥200 mg sodium", str(len(useful))],
                 ["Cheapest per 1,000 mg sodium",
                  f"{cheap['brand']} {cheap['product']}, {money(lo)}"],
                 ["Most expensive per 1,000 mg sodium",
                  f"{dear['brand']} {dear['product']}, {money(hi)}"],
                 ["Cost spread per 1,000 mg sodium", f"{hi / lo:.1f}×"],
                 ["Highest sodium per serving",
                  f"{max_na['brand']} {max_na['product']}, {f0(float(max_na['na_mg']))} mg"],
                 ["Products with zero declared sodium", str(len(zero_na))],
                 ["Products declaring chloride", str(sum(1 for r in products if r['cl_decl'] == 'Y'))],
                 ["Evidence rows", str(len(evidence))],
             ])]
    return "\n".join(parts)


# ------------------------------------------------------------------ link check


LINK_RE = re.compile(r"\[[^\]]*\]\(([^)]+)\)")


def check_links(paths: list[Path]) -> list[str]:
    problems = []
    for path in paths:
        text = path.read_text(encoding="utf-8")
        for target in LINK_RE.findall(text):
            target = target.split("#", 1)[0]
            if not target or target.startswith(("http://", "https://", "mailto:")):
                continue
            resolved = (path.parent / target).resolve()
            if not resolved.exists():
                problems.append(f"{path.relative_to(ROOT)}: broken link -> {target}")
    return problems


# ------------------------------------------------------------------------ main


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()

    products_raw = read_csv("products.csv", PRODUCT_COLUMNS)
    evidence = read_csv("evidence.csv", EVIDENCE_COLUMNS, delimiter="|")
    claims = read_csv("claims.csv", CLAIM_COLUMNS, delimiter="|")
    dosing = read_csv("dosing.csv", DOSING_COLUMNS, delimiter="|")
    standards = read_csv("standards.csv", STANDARD_COLUMNS, delimiter="|")
    refs = read_csv("references.csv", REFERENCE_COLUMNS)

    ref_ids = {r["id"] for r in refs}
    if len(ref_ids) != len(refs):
        sys.exit("error: duplicate reference ids")

    validate_products(products_raw)
    validate_evidence(evidence, ref_ids)
    validate_claims(claims, {r["id"] for r in evidence}, ref_ids)
    validate_dosing(dosing, ref_ids)
    validate_standards(standards, ref_ids)

    products = enrich(products_raw)

    outputs = {
        GENERATED / "key-numbers.md": build_key_numbers(products, evidence),
        GENERATED / "product-comparison.md": build_product_comparison(products),
        GENERATED / "value-ranking.md": build_value_ranking(products),
        GENERATED / "composition-audit.md": build_composition(products),
        GENERATED / "evidence-tables.md": build_evidence(evidence, {r["id"]: r for r in refs}),
        GENERATED / "claims-table.md": build_claims(claims),
        GENERATED / "dosing-table.md": build_dosing(dosing),
        GENERATED / "standards.md": build_standards(standards),
        GENERATED / "product-sources.md": build_product_sources(products_raw),
        DOCS / "references.md": build_references(refs),
    }

    GENERATED.mkdir(parents=True, exist_ok=True)
    stale = []
    for path, content in outputs.items():
        if args.check:
            existing = path.read_text(encoding="utf-8") if path.exists() else None
            if existing != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding="utf-8", newline="\n")

    markdown = sorted(DOCS.rglob("*.md")) + sorted((ROOT / "report").glob("*.md")) + [ROOT / "README.md"]
    links = check_links([p for p in markdown if p.exists()])

    if args.check:
        if stale:
            print("stale generated files:")
            for s in stale:
                print("  " + s)
        for problem in links:
            print("broken link: " + problem)
        if stale or links:
            return 1
        print(f"ok: {len(products)} products, {len(evidence)} evidence rows, {len(refs)} references")
        return 0

    for problem in links:
        print("broken link: " + problem)
    print(f"wrote {len(outputs)} files: {len(products)} products, {len(evidence)} evidence rows, "
          f"{len(claims)} claims, {len(refs)} references")
    return 1 if links else 0


if __name__ == "__main__":
    raise SystemExit(main())
